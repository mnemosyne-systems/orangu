// The three codebooks *below* `IQ1_S`, each a narrower selection from the
// very same 2048 lattice points [`IQ1S_GRID`] holds.
//
// The whole of what these quantizations change is the width of the index:
// `IQ1_S` spends 11 of its 1.5625 bits per weight on the codebook index,
// so shrinking the codebook is the only field with room to give. Every
// other field keeps its `IQ1_S` meaning — the `f16` super-block scale, the
// 3-bit sub-block scale, the `±0.125` delta — which is why the
// dequantizers differ from `IQ1_S`'s only in how they reassemble the
// index.
//
// A narrower grid is *not* a prefix of a wider one: each was chosen by its
// own search over the same lattice, so the tables are separate rather than
// three lengths of one. What they do share is membership — every entry of
// all three appears in [`IQ1S_GRID`] — which is the property the test at
// the bottom checks, and one no corrupted transcription would keep.

